#!/usr/bin/env python3
"""Generate browsable Markdown pages from the existing index metadata."""

import argparse
import html
import json
from pathlib import Path
from urllib.parse import quote, urlsplit

ROOT = Path(__file__).resolve().parent.parent
BACKENDS = ("lucene", "faiss")
NOTICE = "<!-- Generated by scripts/generate_catalog.py. Do not edit directly. -->\n"
USAGE = {
    "lucene": (
        "[Anserini](https://github.com/castorini/anserini/blob/master/docs/prebuilt-indexes.md) · "
        "[Pyserini](https://github.com/castorini/pyserini/blob/master/docs/prebuilt-indexes.md)"
    ),
    "faiss": "[Pyserini](https://github.com/castorini/pyserini/blob/master/docs/prebuilt-indexes.md)",
}


def is_web_url(url):
    parsed = urlsplit(url)
    return parsed.scheme in ("http", "https") and bool(parsed.netloc)


def text(value):
    """Escape metadata text for Markdown, including table cells."""
    value = html.escape(str(value), quote=False).replace("\n", " ").replace("\r", " ")
    for char in "\\`*_{}[]()#+-.!|":
        value = value.replace(char, "\\" + char)
    return value


def code(value):
    return "<code>" + html.escape(str(value)).replace("|", "&#124;") + "</code>"


def link(label, url):
    if not is_web_url(url):
        return None
    return f"[{text(label)}](<{quote(url, safe=':/?#[]@!$&%*+,;=~-._')}>)"


def size_label(size):
    for unit, divisor in (("TiB", 1024**4), ("GiB", 1024**3), ("MiB", 1024**2), ("KiB", 1024)):
        if size >= divisor:
            return f"{size / divisor:.2f} {unit}"
    return f"{size} B"


def table(headers, rows, right_aligned=()):
    """Render a Markdown table with aligned columns in the source file."""
    widths = [
        max(3, len(header), *(len(row[column]) for row in rows))
        for column, header in enumerate(headers)
    ]

    def render_row(cells):
        padded = [
            cell.rjust(width) if column in right_aligned else cell.ljust(width)
            for column, (cell, width) in enumerate(zip(cells, widths))
        ]
        return "| " + " | ".join(padded) + " |"

    separators = [
        "-" * (width - 1) + ":" if column in right_aligned else "-" * width
        for column, width in enumerate(widths)
    ]
    return [render_row(headers), render_row(separators), *(render_row(row) for row in rows)]


class CatalogMetadata:
    """Load index metadata and validate its local README paths."""

    def __init__(self, root):
        self.root = Path(root)
        self.readme_folder = self.root / "docs" / "index-readmes"

    def load_groups(self):
        groups = []
        for backend in BACKENDS:
            manifest = self.root / backend / "manifest.json"
            filenames = json.loads(manifest.read_text(encoding="utf-8"))
            seen = set()
            for filename in sorted(filenames):
                if (
                    Path(filename).name != filename
                    or not filename.endswith(".json")
                    or filename == "manifest.json"
                ):
                    raise ValueError(f"Invalid metadata filename: {filename}")
                group = self._load_group(backend, filename)
                for entry in group["entries"]:
                    name = entry["name"]
                    if name in seen:
                        raise ValueError(f"Duplicate index ID: {backend}:{name}")
                    seen.add(name)
                    if entry["readme_local"] is not None:
                        self._validate_readme(f"{backend}:{name}", entry["readme_local"])
                groups.append(group)
        return groups

    def _load_group(self, backend, filename):
        source = f"{backend}/{filename}"
        data = json.loads((self.root / source).read_text(encoding="utf-8"))
        records = ((row["name"], row) for row in data) if backend == "lucene" else data.items()
        entries = [self._normalize_entry(backend, name, row) for name, row in records]
        return {
            "backend": backend,
            "slug": Path(filename).stem,
            "source": source,
            "entries": sorted(entries, key=lambda entry: entry["name"]),
        }

    @staticmethod
    def _normalize_entry(backend, name, row):
        return {
            "name": name,
            "backend": backend,
            "type": row.get("type"),
            "corpus": row.get("corpus") or row.get("corpus_index"),
            "texts": row.get("texts"),
            "description": row["description"],
            "filename": row["filename"],
            "urls": row["urls"],
            "readme_local": row.get("readme_local"),
            "size": row["size"],
            "md5": row["md5"],
            "note": row.get("note"),
        }

    def _validate_readme(self, reference, name):
        if (
            not isinstance(name, str)
            or not name
            or "\\" in name
            or Path(name).is_absolute()
            or ".." in Path(name).parts
            or name != Path(name).as_posix()
            or name == "."
        ):
            raise ValueError(f"Invalid local README path for {reference}: {name}")
        path = self.readme_folder / name
        if not path.is_file() or self.readme_folder.resolve() not in path.resolve().parents:
            raise ValueError(f"Missing or out-of-directory README for {reference}: {name}")


class CatalogRenderer:
    """Render catalog pages without reading or writing files."""

    def render(self, groups):
        outputs = {
            self._group_path(group): self.render_group(group)
            for group in groups
        }
        outputs["README.md"] = self.render_overview(groups)
        return outputs

    @staticmethod
    def _group_path(group):
        return f"{group['backend']}/{group['slug']}.md"

    @staticmethod
    def _readme_link(entry):
        path = entry["readme_local"]
        if path:
            return f"[README](../../index-readmes/{quote(path)})"
        return "—"

    @staticmethod
    def _hugging_face_links(entry):
        urls = list(dict.fromkeys(
            url for url in entry["urls"]
            if urlsplit(url).hostname == "huggingface.co" and is_web_url(url)
        ))
        return " · ".join(
            link("Hugging Face" if len(urls) == 1 else f"Hugging Face {i}", url)
            for i, url in enumerate(urls, 1)
        ) or "—"

    @staticmethod
    def _hugging_face_pages(group):
        """Collect dataset repository pages from the group's artifact URLs."""
        repositories = set()
        for entry in group["entries"]:
            for url in entry["urls"]:
                parsed = urlsplit(url)
                if parsed.hostname != "huggingface.co" or not is_web_url(url):
                    continue
                parts = parsed.path.strip("/").split("/")
                if len(parts) >= 3 and parts[0] == "datasets" and all(parts[1:3]):
                    repositories.add("/".join(parts[1:3]))
        return " · ".join(
            link(repository, f"https://huggingface.co/datasets/{repository}")
            for repository in sorted(repositories)
        ) or "—"

    def render_overview(self, groups):
        lines = [
            NOTICE,
            "# Prebuilt index catalog", "",
            "[Repository home](../../README.md)", "",
            "Browse by backend and collection below. Each page lists index IDs, descriptions, downloads, and available README links.", "",
            "See [index documentation](../index-readmes/README.md) for build and usage instructions. A dash (—) indicates that no link is available.", "",
            "Index availability depends on your Anserini or Pyserini version. Reported sizes may differ from download or extracted sizes.", "",
        ]
        for backend in BACKENDS:
            selected = [group for group in groups if group["backend"] == backend]
            count = sum(len(group["entries"]) for group in selected)
            lines.extend([
                f"## {backend.title()}", "",
                f"{count} indexes · Usage: {USAGE[backend]}", "",
            ])
            rows = [
                [
                    f"[{group['slug']}]({self._group_path(group)})",
                    str(len(group["entries"])),
                    self._hugging_face_pages(group),
                ]
                for group in selected
            ]
            lines.extend(table(["Collection", "Indexes", "Hugging Face page"], rows, right_aligned=(1,)))
            lines.append("")
        return "\n".join(lines) + "\n"

    def render_group(self, group):
        backend = group["backend"]
        lines = [
            NOTICE,
            f"# {backend.title()}: {group['slug']}", "",
            "[All indexes](../README.md)", "",
            f"{len(group['entries'])} indexes · [Source metadata](../../../{group['source']})", "",
            f"Usage: {USAGE[backend]}", "",
            "## Indexes", "",
        ]
        rows = [
            self._table_cells(entry, number)
            for number, entry in enumerate(group["entries"], 1)
        ]
        lines.extend(table(["Index ID", "README", "Hugging Face"], rows))
        lines.extend(["", "## Details", ""])
        for number, entry in enumerate(group["entries"], 1):
            lines.extend(self._render_details(entry, number))
        return "\n".join(lines) + "\n"

    def _table_cells(self, entry, number):
        return [
            f"[{code(entry['name'])}](#index-{number})",
            self._readme_link(entry),
            self._hugging_face_links(entry),
        ]

    def _render_details(self, entry, number):
        lines = [
            f'<a id="index-{number}"></a>', "",
            "<details>", f"<summary>{code(entry['name'])}</summary>", "",
            text(entry["description"]), "",
        ]
        if entry["corpus"]:
            lines.append(f"- Corpus: {text(entry['corpus'])}")
        if entry["texts"]:
            lines.append(f"- Text collection: {code(entry['texts'])}")
        if entry["type"]:
            lines.append(f"- Index type: {text(entry['type'])}")
        lines.extend([
            f"- Metadata size: {size_label(entry['size'])}",
            f"- Artifact: {code(entry['filename'])}",
            f"- MD5: {code(entry['md5'])}",
        ])
        downloads = [
            link(f"Download {i} ({urlsplit(url).netloc})", url) or code(url)
            for i, url in enumerate(entry["urls"], 1)
        ]
        lines.append("- Downloads: " + (" · ".join(downloads) or "Not provided"))
        lines.append("- README: " + self._readme_link(entry))
        if entry["note"]:
            lines.append(f"- Note: {text(entry['note'])}")
        lines.extend(["", "</details>", ""])
        return lines


class CatalogGenerator:
    """Coordinate loading, rendering, and checking or writing generated pages."""

    def __init__(self, root):
        self.root = Path(root)
        self.folder = self.root / "docs" / "catalog"
        self.metadata = CatalogMetadata(self.root)

    def run(self, check=False):
        groups = self.metadata.load_groups()
        outputs = CatalogRenderer().render(groups)
        stale = self._update_pages(outputs, check)
        if stale:
            print("Run python scripts/generate_catalog.py to regenerate the catalog.")
            return 1
        print(f"{'Checked' if check else 'Generated'} {len(outputs)} catalog pages.")
        return 0

    def _update_pages(self, outputs, check):
        stale = False
        for relative, content in sorted(outputs.items()):
            path = self.folder / relative
            if check:
                if not path.exists() or path.read_text(encoding="utf-8") != content:
                    print(f"Stale or missing: {path.relative_to(self.root)}")
                    stale = True
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
        for path in self._obsolete_pages(outputs):
            if check:
                print(f"Obsolete generated page: {path.relative_to(self.root)}")
                stale = True
            else:
                path.unlink()
        return stale

    def _obsolete_pages(self, outputs):
        for path in sorted(self.folder.rglob("*.md")):
            relative = path.relative_to(self.folder).as_posix()
            if relative not in outputs and path.read_text(encoding="utf-8").startswith(NOTICE):
                yield path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check generated pages without modifying files.")
    args = parser.parse_args()
    return CatalogGenerator(ROOT).run(check=args.check)


if __name__ == "__main__":
    raise SystemExit(main())
